//============================================================================
// top_tang20k.v -- Tang Nano 20K (GW2AR-18) board wrapper
//
// The 27 MHz crystal feeds two PLLs: the system clock (sys_pll.v) for the CPU,
// memory and peripherals, and the pixel clock (video_pll.v) for the display,
// 25.2 MHz for 640x480 or 64.8 MHz for 1024x768. video.v's line buffer is the crossing between them.
//
// The serial port goes to the onboard BL616, which presents it to the host as
// a USB serial device -- no external adapter is needed. DIVISOR is the system
// clock over 115200, rounded: well inside the ~2% an 8N1 link tolerates.
//
// The board's LEDs are common anode, so they light on a logic low; `soc` drives
// them active high and we invert here.
//============================================================================
`default_nettype none

// Absolute path to the ROM image, generated by `make`. $readmemh resolves
// relative to the tool's working directory, and Gowin runs synthesis from
// impl/gwsynthesis/, so a relative path silently yields a blank ROM -- the
// tools report only a warning and build a working bitstream around it.
`include "rom_path.vh"

module top_tang20k #(
    parameter ROM_HEX  = `ROM_HEX_PATH,
    parameter FONT_HEX = `FONT_HEX_PATH
) (
    input  wire       clk,          // 27 MHz crystal
    input  wire       rst,          // S1: idle low, HIGH when pressed
    output wire       led,          // active low: the power LED and the soft-power off line (power.v)
    input  wire       pwr_key_n,    // the carrier's power key, low while down (FPGA 53, DDC clock)
    output wire       uart_tx,      // to BL616 (FPGA -> host)
    input  wire       uart_rx,      // from BL616 (host -> FPGA)
    // In-package SDRAM. These port names are reserved: the Gowin tools connect
    // them to the die inside the package, so unlike every other signal here
    // they must NOT appear in the .cst.
    output wire        O_sdram_clk,
    output wire        O_sdram_cke,
    output wire        O_sdram_cs_n,
    output wire        O_sdram_cas_n,
    output wire        O_sdram_ras_n,
    output wire        O_sdram_wen_n,
    inout  wire [31:0] IO_sdram_dq,
    output wire [10:0] O_sdram_addr,
    output wire [1:0]  O_sdram_ba,
    output wire [3:0]  O_sdram_dqm,
    // Apple Desktop Bus: drive pulls the bus low, sense reads it back.
    // Level shifting to the bus's 5V is external.
    output wire        adb_drive,
    input  wire        adb_sense,
    // External peripheral bus (external_bus.v, docs/Hardware.md). ext_d is a
    // real bidirectional pin group; everything else is unidirectional.
    output wire [3:0]  ext_a,
    inout  wire [7:0]  ext_d,
    output wire [2:0]  ext_sel,
    output wire        ext_sel_en_n,
    output wire        ext_rd_n,
    output wire        ext_wr_n,
    output wire        ext_res_n,
    input  wire        ext_irq_n,
    // DMA: the 53C80's and the 82077AA's requests, and terminal count
    input  wire [1:0]  dma_drq,
    output wire        dma_tc,
    // Sound: I2S to the onboard MAX98357A; amp_en drives its SD_MODE.
    output wire        i2s_bclk,
    output wire        i2s_lrck,
    output wire        i2s_din,
    output wire        amp_en,
    // The microSD slot in SPI mode: CLK, CMD, D0 and D3.
    output wire        sd_clk,
    output wire        sd_mosi,
    input  wire        sd_miso,
    output wire        sd_cs_n,
    // HDMI. A differential pair takes both pin numbers on the _p port only.
    output wire        tmds_clk_p,
    output wire        tmds_clk_n,
    output wire [2:0]  tmds_d_p,
    output wire [2:0]  tmds_d_n
);
    // The system clock: 27 * (FBDIV+1) / (IDIV+1). SYS_HZ must match it --
    // the serial divisor, the timer's prescaler, SDRAM refresh, the external
    // bus's strobes, ADB, SD and sound all count from it -- and be a multiple
    // of 100 kHz, 25.2 MHz or more. tang_nano_20k.sdc has the same ratio.
    localparam integer SYS_IDIV  = 1;              // /2
    localparam integer SYS_FBDIV = 2;              // x3: 40.5 MHz
    localparam integer SYS_ODIV  = 16;             // VCO 648 MHz
    localparam integer SYS_HZ    = 40_500_000;
    localparam integer DIVISOR   = (SYS_HZ + 57_600) / 115_200;

    // The resolution, from `make bit RES=1024` (rom_path.vh): 1024x768 at a
    // 64.8 MHz pixel clock, else 640x480 at 25.2 MHz.
`ifdef VIDEO_RES
    localparam XGA = (`VIDEO_RES == 1024);
`else
    localparam XGA = 0;
`endif

    //------------------------------------------------------------------
    // Reset: hold for ~4 ms after configuration, and while S1 is pressed.
    // The button is synchronized before it is allowed to reset anything.
    //------------------------------------------------------------------
    wire clk_pix, clk_pix5, clk_ser, vpll_locked;
    wire ser_rst_n, div_rst_n;
    video_pll #(.XGA(XGA)) u_vpll (.clk27(clk), .rst_n(1'b1), .div_rst_n(div_rst_n),
                      .calib(1'b0),
                      .clk_pix(clk_pix), .clk_pix5(clk_pix5), .clk_ser(clk_ser),
                      .locked(vpll_locked));

    wire sys_clk, spll_locked;
    sys_pll #(.IDIV_SEL(SYS_IDIV), .FBDIV_SEL(SYS_FBDIV), .ODIV_SEL(SYS_ODIV))
        u_spll (.clk27(clk), .clk(sys_clk), .locked(spll_locked));

    wire pll_locked = vpll_locked & spll_locked;

    reg [16:0] por = 17'd0;
    reg [1:0]  btn = 2'b11;
    wire       por_done = por[16];

    always @(posedge sys_clk) begin
        if (!por_done && pll_locked) por <= por + 1'b1;
        btn <= {btn[0], rst};
    end

    // S1 is ACTIVE HIGH on this board: measured idle low, going high when
    // pressed (test/btntest.v). The conventional `por_done & btn[1]` therefore
    // held the whole SoC in reset forever -- the first hardware fault found
    // here -- so the button is inverted instead.
    //
    // Holding S1 resets the CPU, the cache and the SDRAM controller together,
    // which re-runs the SDRAM power-up sequence; `soc.v` keeps the CPU in reset
    // until that finishes.
    //
    // The PLLs' lock only gates the power-on count: once that has run, a drop
    // in LOCK no longer resets the SoC. On the board the system PLL's LOCK
    // fell at least once while running (a sticky flag caught it during the
    // Nov 2026 HDMI hunt), and with it in this term every such glitch reset
    // the SoC at random -- or, ANDed straight into the asynchronous resets,
    // reset only some of it.
    wire rst_n = por_done & ~btn[1];

    // The PLLs' LOCKs on the 27 MHz crystal clock, which depends on neither:
    // {video, system}. The video PLL's drives the HDMI reset sequencer below.
    reg [1:0] lk_s = 2'b00;
    reg lk_run = 1'b0;      // the video PLL has locked since its last release
                            // (the sequencer below); its own resets drop lock
    always @(posedge clk) lk_s <= {vpll_locked, spll_locked};

    //------------------------------------------------------------------
    // The pixel domain's reset: asserted with the system's, released two
    // pixel clocks later, so its release is synchronous to clk_pix.
    reg [1:0] pix_rst = 2'b00;
    always @(posedge clk_pix or negedge rst_n)
        if (!rst_n) pix_rst <= 2'b00;
        else        pix_rst <= {pix_rst[0], 1'b1};
    wire pix_rst_n = pix_rst[1];

    wire [7:0] v_r, v_g, v_b;
    wire       v_hs, v_vs, v_de;

    // The HDMI serializers' reset and the pixel clock divider's (video_pll.v).
    // Each is released by a flop on the clock of the cell it goes to: the
    // divider's by rel_d on clk_pix5, the serializers' by rel_s on clk_ser,
    // their own PLL output, two stages, so they start one 5x clock after the
    // divider. Each release lands a fraction of a cycle after the edge of its
    // own clock, the same every time, and the timing report's recovery check
    // covers it. The whole thing is held until the video PLL has locked and
    // 16 crystal clocks more, and again if the lock drops. S1 does not touch
    // it. Holding the divider stops clk_pix.
    //
    // History (Nov 2026, the 1024x768 sync loss): Gowin's OSER10 copies each
    // word into its shifter on a count of the 5x clock that starts when its
    // RESET is released, and the divider's output phase starts from its
    // release too. Released from a flop here while the 5x clock ran, the
    // release reached the serializers 0.2-0.4 ns after an edge (the recovery
    // violations in the timing report), so each caught that edge or the next
    // at random: a draw per release, kept for the life of the bitstream.
    // Making the release deterministic (the clock stopped, then a shift
    // register with a run-time lag at $03B1) showed which draws were
    // catastrophic (black), but the rest still flashed under blitter
    // traffic, with our serializers and with Gowin's DVI_TX IP alike, until
    // the serializers got a PLL output of their own (video_pll.v): on that,
    // every lag and every phase of the output was steady, so the knobs went,
    // and so did the software re-release that drove the sweeps.
    reg  [4:0] seq_n  = 5'd16;
    reg        run = 1'b0, ser_req_n = 1'b0;
    always @(posedge clk) begin
        if (!run) begin
            if (!lk_s[1])          seq_n <= 5'd16;
            else if (seq_n != 0)   seq_n <= seq_n - 1'b1;
            else begin ser_req_n <= 1'b1; run <= 1'b1; lk_run <= 1'b0; end
        end else if (lk_run & ~lk_s[1]) begin
            ser_req_n <= 1'b0; run <= 1'b0; lk_run <= 1'b0; seq_n <= 5'd16;
        end else if (lk_s[1])
            lk_run <= 1'b1;
    end
    reg       rel_d = 1'b0;             // the divider's release
    reg [1:0] rel_s = 2'b00;            // the serializers', one 5x clock later
    always @(posedge clk_pix5 or negedge ser_req_n)
        if (!ser_req_n) rel_d <= 1'b0;
        else            rel_d <= 1'b1;
    always @(posedge clk_ser or negedge ser_req_n)
        if (!ser_req_n) rel_s <= 2'b00;
        else            rel_s <= {rel_s[0], 1'b1};
    assign div_rst_n = rel_d;
    assign ser_rst_n = rel_s[1];

    // The encoders come out of reset two pixel clocks after the serializers,
    // the pixel clock having started again by then.
    reg [1:0] enc_s = 2'b00;
    always @(posedge clk_pix or negedge ser_rst_n)
        if (!ser_rst_n) enc_s <= 2'b00;
        else            enc_s <= {enc_s[0], 1'b1};
    wire hdmi_rst_n = enc_s[1];

    // Our own TMDS encoders and serializers (hdmi_out.v, ELVDS pins). The
    // serializers' 5x clock is clk_ser, their own PLL output (video_pll.v).
    // Gowin's DVI_TX IP in their place (Nov 2026, TLVDS pins) lost sync the
    // same way they did before the fix, so it was not kept.
    hdmi_out u_hdmi (
        .clk_pix(clk_pix), .clk_pix5(clk_ser), .rst_n(hdmi_rst_n),
        .ser_rst_n(ser_rst_n),
        .red(v_r), .green(v_g), .blue(v_b),
        .hsync(v_hs), .vsync(v_vs), .de(v_de),
        .tmds_clk_p(tmds_clk_p), .tmds_clk_n(tmds_clk_n),
        .tmds_d_p(tmds_d_p), .tmds_d_n(tmds_d_n)
    );

    wire led_active_high;

    // Data bus tristate. Inferred rather than instantiated as IOBUF: the Gowin
    // mapper recognises this form and it stays simulatable.
    wire [7:0] ext_d_out;
    wire [7:0] ext_d_in = ext_d;
    wire       ext_d_oe;
    assign ext_d = ext_d_oe ? ext_d_out : 8'bz;

    soc #(
        .ROM_HEX(ROM_HEX),
        .FONT_HEX(FONT_HEX),
        .DIVISOR(DIVISOR),
        .SYS_HZ(SYS_HZ),
        .XGA(XGA),
        .MAP(`ROM_MAP),
        .ROM_BITS(`ROM_BITS_DEF),
        .ROM_BASE(`ROM_BASE_DEF)
    ) u_soc (
        .clk(sys_clk),
        .rst_n(rst_n),
        .rxd(uart_rx),
        .txd(uart_tx),
        .led(led_active_high), .pwr_key_n(pwr_key_n),
        .dbg_addr(), .dbg_vld(), .dbg_we(), .dbg_stopped(),
        .dbg_cache_hits(), .dbg_cache_misses(),
        .sdram_a(O_sdram_addr), .sdram_ba(O_sdram_ba), .sdram_dq(IO_sdram_dq),
        .sdram_dqm(O_sdram_dqm), .sdram_cs_n(O_sdram_cs_n),
        .sdram_ras_n(O_sdram_ras_n), .sdram_cas_n(O_sdram_cas_n),
        .sdram_we_n(O_sdram_wen_n), .sdram_cke(O_sdram_cke),
        .sdram_clk(O_sdram_clk),
        .clk_pix(clk_pix), .pix_rst_n(pix_rst_n),
        .vid_red(v_r), .vid_green(v_g), .vid_blue(v_b),
        .vid_hsync(v_hs), .vid_vsync(v_vs), .vid_de(v_de),
        .adb_drive(adb_drive), .adb_sense(adb_sense),
        .ext_a(ext_a), .ext_d_in(ext_d_in), .ext_d_out(ext_d_out),
        .ext_d_oe(ext_d_oe), .ext_sel(ext_sel), .ext_sel_en_n(ext_sel_en_n),
        .ext_rd_n(ext_rd_n), .ext_wr_n(ext_wr_n),
        .ext_res_n(ext_res_n), .ext_irq_n(ext_irq_n),
        .dma_drq(dma_drq), .dma_tc(dma_tc),
        .i2s_bclk(i2s_bclk), .i2s_lrck(i2s_lrck), .i2s_din(i2s_din),
        .amp_en(amp_en),
        .sd_clk(sd_clk), .sd_mosi(sd_mosi), .sd_cs_n(sd_cs_n), .sd_miso(sd_miso)
    );

    assign led = ~led_active_high;
endmodule

`default_nettype wire
